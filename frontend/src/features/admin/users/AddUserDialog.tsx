import { useState, type FormEvent } from 'react'
import * as usersApi from '@/api/api.admin.users'
import { ApiError } from '@/api/client'
import { Banner } from '@/components/ui/Banner'
import { BottomSheet } from '@/components/ui/BottomSheet'
import { Button } from '@/components/ui/Button'
import { Modal } from '@/components/ui/Modal'
import { SegmentedControl } from '@/components/ui/SegmentedControl'
import { TextField } from '@/components/ui/TextField'
import type { AdminUser } from '@/core/types'
import { isValidEmail } from '@/core/utils'
import { useIsDesktop } from '@/hooks/useMediaQuery'
import { TemporaryPassword } from './TemporaryPassword'
import './AddUserDialog.css'

const ROLES = ['Student', 'Admin'] as const
const STATUSES = ['Active', 'Inactive'] as const

interface Errors {
  name?: string
  email?: string
}

interface AddUserDialogProps {
  open: boolean
  onClose: () => void
  onCreated: (user: AdminUser) => void
}

/**
 * Add user: Modal on desktop, BottomSheet on mobile. After saving it shows the
 * temporary password generated by the backend. Mount with a fresh `key` per opening.
 */
export function AddUserDialog({ open, onClose, onCreated }: AddUserDialogProps) {
  const isDesktop = useIsDesktop()
  const [name, setName] = useState('')
  const [email, setEmail] = useState('')
  const [role, setRole] = useState<(typeof ROLES)[number]>('Student')
  const [status, setStatus] = useState<(typeof STATUSES)[number]>('Active')
  const [errors, setErrors] = useState<Errors>({})
  const [banner, setBanner] = useState<string | null>(null)
  const [saving, setSaving] = useState(false)
  const [created, setCreated] = useState<{ email: string; password: string } | null>(null)

  const onSubmit = async (event: FormEvent) => {
    event.preventDefault()
    const normalized = email.trim().toLowerCase()
    const next: Errors = {
      name: name.trim() ? undefined : 'Enter a full name.',
      email: isValidEmail(normalized) ? undefined : 'Enter a valid email address.',
    }
    setErrors(next)
    setBanner(null)
    if (next.name || next.email) return

    setSaving(true)
    try {
      const result = await usersApi.createUser({
        fullName: name,
        email: normalized,
        role: role === 'Admin' ? 'admin' : 'student',
        isActive: status === 'Active',
      })
      onCreated(result.user)
      setCreated({ email: result.user.email, password: result.temporaryPassword })
    } catch (error) {
      if (error instanceof ApiError && error.status === 409) {
        setErrors({ email: 'A user with this email already exists.' })
      } else {
        setBanner(error instanceof ApiError ? error.message : 'Could not add this user.')
      }
    } finally {
      setSaving(false)
    }
  }

  const content = created ? (
    <div className="add-user">
      <TemporaryPassword password={created.password} email={created.email} />
      <p className="add-user__helper">They can log in with it right away.</p>
      <div className={isDesktop ? 'add-user__actions' : 'add-user__stack'}>
        <Button size={isDesktop ? 'md' : 'lg'} block={!isDesktop} onClick={onClose}>
          Done
        </Button>
      </div>
    </div>
  ) : (
    <form className="add-user" onSubmit={onSubmit} noValidate>
      {banner && <Banner>{banner}</Banner>}
      <TextField
        label="Full name"
        value={name}
        error={errors.name}
        autoComplete="off"
        data-autofocus
        onChange={(e) => {
          setName(e.target.value)
          setErrors((prev) => ({ ...prev, name: undefined }))
        }}
      />
      <TextField
        label="Email"
        type="email"
        value={email}
        error={errors.email}
        autoComplete="off"
        onChange={(e) => {
          setEmail(e.target.value)
          setErrors((prev) => ({ ...prev, email: undefined }))
        }}
      />
      <div className="add-user__status">
        <span className="add-user__label">Role</span>
        <SegmentedControl
          label="Role"
          options={ROLES}
          value={role}
          onChange={setRole}
          fullWidth={!isDesktop}
        />
      </div>
      <div className="add-user__status">
        <span className="add-user__label">Status</span>
        <SegmentedControl
          label="Status"
          options={STATUSES}
          value={status}
          onChange={setStatus}
          fullWidth={!isDesktop}
        />
      </div>
      <p className="add-user__helper">
        A temporary password is generated for them. You'll see it once, after adding.
      </p>
      {isDesktop ? (
        <div className="add-user__actions">
          <Button variant="secondary" onClick={onClose}>
            Cancel
          </Button>
          <Button type="submit" loading={saving}>
            Add user
          </Button>
        </div>
      ) : (
        <div className="add-user__stack">
          <Button type="submit" size="lg" block loading={saving}>
            Add user
          </Button>
          <Button variant="secondary" block onClick={onClose}>
            Cancel
          </Button>
        </div>
      )}
    </form>
  )

  const title = created ? 'User added' : 'Add user'

  return isDesktop ? (
    <Modal open={open} onClose={onClose} title={title} width={480}>
      {content}
    </Modal>
  ) : (
    <BottomSheet open={open} onClose={onClose} title={title}>
      {content}
    </BottomSheet>
  )
}
